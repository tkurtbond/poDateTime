#!/usr/bin/env python3
"""Write test/data/ZoneFilesData.Mod: the TZif files of test/data/zoneinfo/
as hexadecimal text, from which test/vax/ZoneFiles.Mod writes them on VMS
(design Q24). A binary file copied there by FTP comes out as 512-byte
records padded with zeros, so the files go as source instead.

Each file is named on VMS as test/vax/ZoneFiles.Path names it: its form,
an underscore and its last name, in capitals, with each hyphen made an
underscore, and the type .TZIF, so fat/America/New_York is
FAT_NEW_YORK.TZIF.

Usage: tools/zone-files-data.py > test/data/ZoneFilesData.Mod
"""

import os

DIR = "test/data/zoneinfo"
PIECE = 64   # hexadecimal digits a call
CALLS = 200   # calls a procedure, to keep each one small


def vms_name(form, path):
    return (form + "_" + os.path.basename(path)).upper().replace("-", "_") + ".TZIF"


def files():
    found = []
    for form in sorted(os.listdir(DIR)):
        for root, _, names in os.walk(os.path.join(DIR, form)):
            for name in names:
                found.append((form, os.path.join(root, name)))
    found.sort()
    return found


def main():
    calls = []
    seen = set()
    for form, path in files():
        name = vms_name(form, path)
        assert name not in seen, name
        seen.add(name)
        data = open(path, "rb").read().hex()
        for i in range(0, len(data), PIECE):
            calls.append('    v("%s", "%s");' % (name, data[i:i + PIECE]))
    print("MODULE ZoneFilesData;")
    print()
    print("  (* Generated by tools/zone-files-data.py from test/data/zoneinfo/;")
    print("     do not edit. *)")
    print()
    print("  (* a file's VMS name and the next piece of its bytes, in hexadecimal;")
    print("     a file's pieces come together, in order *)")
    print("  TYPE Visit* = PROCEDURE (name, hex: ARRAY OF CHAR);")
    count = 0
    for start in range(0, len(calls), CALLS):
        print()
        print("  PROCEDURE Files%d(v: Visit);" % count)
        print("  BEGIN")
        print(";\n".join(c.rstrip(";") for c in calls[start:start + CALLS]))
        print("  END Files%d;" % count)
        count += 1
    print()
    print("  PROCEDURE Each*(v: Visit);")
    print("  BEGIN")
    print(";\n".join("    Files%d(v)" % i for i in range(count)))
    print("  END Each;")
    print()
    print("  PROCEDURE FileCount*(): LONGINT;")
    print("  BEGIN")
    print("    RETURN %d" % len(seen))
    print("  END FileCount;")
    print()
    print("END ZoneFilesData.")


main()
