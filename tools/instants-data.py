#!/usr/bin/env python3
"""Write test/data/InstantsData.Mod: instants truncated to units that
neither divide a second nor are whole seconds, and some that do, from
Python's integers, which have no width.

Usage: tools/instants-data.py > test/data/InstantsData.Mod
"""

import random

G = 10 ** 9
EARLIEST = -377705116800 * G
LATEST = 253402300799 * G + G - 1
MAX = 2 ** 63 - 1


def truncate(t, unit):
    return max(t - t % unit, EARLIEST)


def instants(rng):
    yield from [EARLIEST, EARLIEST + 1, LATEST, LATEST - 1, 0, -1, 1,
                G - 1, -G, -G - 1, 1793196306 * G + 123456789]
    for _ in range(25):
        yield rng.randint(EARLIEST, LATEST)
    for _ in range(4):
        yield rng.randint(-10 ** 13, 10 ** 13)


def units(rng):
    yield from [3 * 10 ** 6, 7 * 10 ** 6, 4 * 10 ** 8, 16666667, 3,
                G - 1, G + 1, 3 * G // 2, 5 * G // 2,
                86400 * G + 1, 2 ** 62 + 1, MAX, MAX - G,
                # these the two short paths take
                1, 1000, 25 * 10 ** 7, G, 60 * G, 604800 * G]
    for bits in (20, 33, 40, 50, 62):
        yield rng.randint(1, 2 ** bits)


def main():
    rng = random.Random(19700101)
    us = list(units(rng))
    ts = list(instants(rng))
    rows = []
    for u in us:
        for t in ts:
            r = truncate(t, u)
            rows.append((t // G, t % G, u, r // G, r % G))
    print("MODULE InstantsData;")
    print()
    print("  (* Generated by tools/instants-data.py from Python's integers;"
          " do not edit.")
    print("     Each row is an instant's seconds and nanosecond, a unit, and")
    print("     the instant truncated to the unit. *)")
    print()
    print("  TYPE Row* = PROCEDURE (seconds, nanosecond, unit,"
          " truncatedSeconds, truncatedNanosecond: HUGEINT);")
    print()
    chunk = 250
    for i in range(0, len(rows), chunk):
        print("  PROCEDURE Part%d(r: Row);" % (i // chunk))
        print("  BEGIN")
        for row in rows[i:i + chunk]:
            print("    r(%d, %d, %d, %d, %d);" % row)
        print("  END Part%d;" % (i // chunk))
        print()
    print("  PROCEDURE Each*(r: Row);")
    print("  BEGIN")
    for i in range(0, len(rows), chunk):
        print("    Part%d(r);" % (i // chunk))
    print("  END Each;")
    print()
    print("  PROCEDURE Count*(): LONGINT;")
    print("  BEGIN")
    print("    RETURN %d" % len(rows))
    print("  END Count;")
    print()
    print("END InstantsData.")


main()
