#!/usr/bin/env python3
"""Write test/data/PatternsData.Mod: date-times written by glibc's
strftime, for TimeStrings.Format and Parse (design 10.2).

The rows keep to what glibc and TimeStrings agree on (Q18, Q21): the
years 1000..9999, with week-years in them too; whole-minute offsets; and
%s only at offset 0, since glibc's %s reads the fields as local time,
which TZ=UTC0 makes UTC. %N, %:z and %::z, which glibc lacks, are left to
the test. strftime is called through ctypes, so that the C library's own
%z, %Z and week numbers are compared, not Python's.

Usage: tools/patterns-data.py > test/data/PatternsData.Mod
"""

import ctypes
import ctypes.util
import datetime
import os
import random
import time

PATTERNS = [
    "%Y-%m-%d %H:%M:%S %z %Z|%C %y %G %g %V %U %W %u %w %j|%a %A %b %B %h|"
    "%I %l %p %P %k %e",
    "%c|%F %T|%R|%D|%x|%X|%%|%-d %_m %0e %^a %^B %-H %_H %-j %^p %-I %-y %-C %-Y",
]
# only at offset 0
SECONDS = "%s %z"
OFFSETS = [0, -14400, -18000, 19800, -12600, 20700, 45900, 50400, -43200,
           -10800, 3600, -60, 93540, -93540]
# offsets whose abbreviation is numeric, as tzdata writes them
NUMERIC = {19800: "+0530", -10800: "-03", 45900: "+1245", -60: "-0001"}


class Tm(ctypes.Structure):
    _fields_ = [(name, ctypes.c_int) for name in
                "sec min hour mday mon year wday yday isdst".split()] + [
        ("gmtoff", ctypes.c_long), ("zone", ctypes.c_char_p)]


libc = ctypes.CDLL(ctypes.util.find_library("c"))
libc.strftime.argtypes = [ctypes.c_char_p, ctypes.c_size_t, ctypes.c_char_p,
                          ctypes.POINTER(Tm)]


def abbreviation(offset):
    if offset == 0:
        return "UTC"
    return NUMERIC.get(offset, "XST")


def strftime(pattern, dt, offset):
    zone = abbreviation(offset).encode()
    tm = Tm(dt.second, dt.minute, dt.hour, dt.day, dt.month - 1,
            dt.year - 1900, dt.isoweekday() % 7, dt.timetuple().tm_yday - 1,
            0, offset, zone)
    buffer = ctypes.create_string_buffer(400)
    libc.strftime(buffer, 400, pattern.encode(), ctypes.byref(tm))
    return buffer.value.decode()


def date_times(rng):
    first = datetime.date(1000, 1, 8).toordinal()
    last = datetime.date(9999, 12, 24).toordinal()
    days = [datetime.date.fromordinal(rng.randint(first, last)) for _ in range(250)]
    # the ends of years, where the week numbers turn over
    for year in (1600, 1900, 2000, 2004, 2020, 2021, 2026, 2027, 2100, 9998):
        days += [datetime.date(year, 12, d) for d in range(28, 32)]
        days += [datetime.date(year + 1, 1, d) for d in range(1, 8)]
    for day in days:
        hour = rng.choice([0, 1, 11, 12, 13, 23, rng.randrange(24)])
        yield (datetime.datetime(day.year, day.month, day.day, hour,
                                 rng.randrange(60), rng.randrange(60)),
               rng.choice(OFFSETS))


def main():
    os.environ["TZ"] = "UTC0"
    time.tzset()
    rng = random.Random(20261028)
    rows = []
    for dt, offset in date_times(rng):
        patterns = PATTERNS + ([SECONDS] if offset == 0 else [])
        for pattern in patterns:
            rows.append('r(%d, %d, %d, %d, %d, %d, %d, "%s",\n      "%s",\n      "%s");' % (
                dt.year, dt.month, dt.day, dt.hour, dt.minute, dt.second, offset,
                abbreviation(offset), pattern, strftime(pattern, dt, offset)))
    chunk = 250
    print("MODULE PatternsData;")
    print()
    print("  (* Generated by tools/patterns-data.py from glibc's strftime;"
          " do not edit. *)")
    print()
    print("  (* a date-time, its offset and abbreviation, a pattern, and what"
          " strftime\n     writes *)")
    print("  TYPE Row* = PROCEDURE (year, month, day, hour, minute, second,"
          " offset: LONGINT;\n"
          "                         abbreviation, pattern, text: ARRAY OF CHAR);")
    print()
    for i in range(0, len(rows), chunk):
        print("  PROCEDURE Rows%d(r: Row);" % (i // chunk))
        print("  BEGIN")
        for row in rows[i:i + chunk]:
            print("    " + row)
        print("  END Rows%d;" % (i // chunk))
        print()
    print("  PROCEDURE Each*(r: Row);")
    print("  BEGIN")
    for i in range(0, len(rows), chunk):
        print("    Rows%d(r);" % (i // chunk))
    print("  END Each;")
    print()
    print("  PROCEDURE Count*(): LONGINT;")
    print("  BEGIN")
    print("    RETURN %d" % len(rows))
    print("  END Count;")
    print()
    print("END PatternsData.")


main()
