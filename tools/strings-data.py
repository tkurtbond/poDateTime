#!/usr/bin/env python3
"""Write test/data/StringsData.Mod: instants at offsets, written by
Python's datetime.isoformat, for TimeStrings.OffsetDateTime and
ReadInstant. Python's datetime has years 1..9999 and microseconds only,
and offsets below 24 hours, so the rows keep within those; the other
cases are in test/TimeStringsTest.Mod.

Usage: tools/strings-data.py > test/data/StringsData.Mod
"""

import datetime
import random

UTC = datetime.timezone.utc
EPOCH = datetime.datetime(1970, 1, 1, tzinfo=UTC)
FIRST = int((datetime.datetime(1, 1, 2, tzinfo=UTC) - EPOCH).total_seconds())
LAST = int((datetime.datetime(9999, 12, 30, tzinfo=UTC) - EPOCH).total_seconds())

# seconds east of UTC, some with seconds of their own, as local mean
# times have: Amsterdam's +00:19:32, Dublin's -00:25:21
OFFSETS = [0, -18000, -14400, 19800, -12600, 50400, -43200, 1172, -1521,
           20700, 45900, -1, 86399, -86399]
TIMESPECS = {0: "seconds", 3: "milliseconds", 6: "microseconds"}


def instants(rng):
    yield from [(0, 0), (-1, 999999), (FIRST, 0), (LAST, 999999),
                (1793196306, 123456), (1483228799, 500000)]
    for _ in range(40):
        yield rng.randint(FIRST, LAST), rng.randrange(10 ** 6)
    for _ in range(20):
        yield rng.randint(-10 ** 9, 3 * 10 ** 9), rng.choice(
            [0, 500000, 120000, 123000, 1, rng.randrange(10 ** 6)])


def main():
    rng = random.Random(20261028)
    rows = []
    for seconds, micro in instants(rng):
        for offset in OFFSETS:
            zone = datetime.timezone(datetime.timedelta(seconds=offset))
            t = EPOCH + datetime.timedelta(seconds=seconds, microseconds=micro)
            local = t.astimezone(zone)
            for digits, spec in TIMESPECS.items():
                text = local.isoformat(timespec=spec)
                if text.endswith("+00:00"):
                    text = text[:-6] + "Z"
                rows.append((seconds, micro * 1000, offset, digits, text))
    print("MODULE StringsData;")
    print()
    print("  (* Generated by tools/strings-data.py from Python's"
          " datetime.isoformat;")
    print("     do not edit. Each row is an instant's seconds and"
          " nanosecond, an")
    print("     offset, a number of fractional digits, and the instant at"
          " that")
    print("     offset written with that many, with Z for an offset of 0."
          " *)")
    print()
    print("  TYPE Row* = PROCEDURE (seconds, nanosecond, offset: HUGEINT;"
          " digits: INTEGER;")
    print("                         text: ARRAY OF CHAR);")
    print()
    chunk = 250
    for i in range(0, len(rows), chunk):
        print("  PROCEDURE Part%d(r: Row);" % (i // chunk))
        print("  BEGIN")
        for row in rows[i:i + chunk]:
            print('    r(%d, %d, %d, %d, "%s");' % row)
        print("  END Part%d;" % (i // chunk))
        print()
    print("  PROCEDURE Each*(r: Row);")
    print("  BEGIN")
    for i in range(0, len(rows), chunk):
        print("    Part%d(r);" % (i // chunk))
    print("  END Each;")
    print()
    print("  PROCEDURE Count*(): LONGINT;")
    print("  BEGIN")
    print("    RETURN %d" % len(rows))
    print("  END Count;")
    print()
    print("END StringsData.")


main()
