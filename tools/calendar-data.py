#!/usr/bin/env python3
"""Write test/data/CalendarData.Mod: dates with their day of the week,
day of the year, ISO week and day number, from Python's datetime.

Python's dates stop at year 1. A year y <= 0 is taken from y + 400k,
which has the same weekdays and ISO weeks, because 400 Gregorian years
are 146 097 days, a whole number of weeks; its day number is moved back
by k * 146 097.

Usage: tools/calendar-data.py > test/data/CalendarData.Mod
"""

import datetime
import random

EPOCH = datetime.date(1970, 1, 1).toordinal()
CYCLE = 146097


def row(year, month, day):
    shift = 0
    while year + 400 * shift < 1:
        shift += 1
    d = datetime.date(year + 400 * shift, month, day)
    week_year, week, weekday = d.isocalendar()
    return (year, month, day, weekday, d.timetuple().tm_yday,
            week_year - 400 * shift, week,
            d.toordinal() - EPOCH - shift * CYCLE)


def dates():
    seen = set()

    def add(y, m, d):
        if (y, m, d) not in seen:
            seen.add((y, m, d))
            yield (y, m, d)

    # the ends of the years and the epoch
    for y, m, d in [(-9999, 1, 1), (-9999, 12, 31), (-1, 12, 31), (0, 1, 1),
                    (0, 2, 29), (1, 1, 1), (1969, 12, 31), (1970, 1, 1),
                    (9999, 1, 1), (9999, 12, 31)]:
        yield from add(y, m, d)
    # every New Year, where ISO weeks change year, in a run of 400 years
    # and in some years before year 1
    for y in list(range(1800, 2201)) + list(range(-404, 5)) + [-9999, 9999]:
        for m, d in [(12, 28), (12, 29), (12, 30), (12, 31)]:
            if y >= -9999 and y <= 9999:
                yield from add(y, m, d)
        for d in range(1, 5):
            yield from add(y, 1, d)
    # leap days around the century rules
    for y in [-400, -100, -4, 1600, 1700, 1800, 1900, 2000, 2100, 2400]:
        yield from add(y, 2, 28)
        yield from add(y, 3, 1)
        if y % 4 == 0 and (y % 100 != 0 or y % 400 == 0):
            yield from add(y, 2, 29)
    # a fixed random sample of the whole range
    rng = random.Random(19700101)
    for _ in range(2000):
        y = rng.randint(-9999, 9999)
        m = rng.randint(1, 12)
        d = rng.randint(1, 28)
        yield from add(y, m, d)


def main():
    rows = [row(*d) for d in dates()]
    print("MODULE CalendarData;")
    print()
    print("  (* Generated by tools/calendar-data.py from Python's datetime;"
          " do not edit.")
    print("     Each row is year, month, day, the day of the week, the day of")
    print("     the year, the ISO week-year and week, and the day number. *)")
    print()
    print("  TYPE Row* = PROCEDURE (year, month, day, weekday, dayOfYear,"
          " weekYear, week: LONGINT;")
    print("                         dayNumber: HUGEINT);")
    print()
    # in pieces, so that no procedure is too long for the VAX
    chunk = 250
    for i in range(0, len(rows), chunk):
        print("  PROCEDURE Part%d(r: Row);" % (i // chunk))
        print("  BEGIN")
        for r in rows[i:i + chunk]:
            print("    r(%d, %d, %d, %d, %d, %d, %d, %d);" % r)
        print("  END Part%d;" % (i // chunk))
        print()
    print("  PROCEDURE Each*(r: Row);")
    print("  BEGIN")
    for i in range(0, len(rows), chunk):
        print("    Part%d(r);" % (i // chunk))
    print("  END Each;")
    print()
    print("  PROCEDURE Count*(): LONGINT;")
    print("  BEGIN")
    print("    RETURN %d" % len(rows))
    print("  END Count;")
    print()
    print("END CalendarData.")


main()
